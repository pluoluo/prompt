def choose(labels, values, many=False):
    options = [{'label': label, 'value': value} for label, value in zip(labels, values)]
    return {'type': 'multi-select' if many else 'select', 'options': options,
            'default': [values[0]] if many else values[0]}


def replace_field(name, labels, alternatives, *, preset_key=None, many=False):
    """Keep the reviewed default instruction, expose shorter selectable alternatives."""
    for group in groups.values():
        for item in group['presets']:
            if preset_key and item['key'] != preset_key:
                continue
            for block in item['sections'].values():
                if name in block['fields']:
                    old = block['fields'][name]
                    block['fields'][name] = choose(labels, [old['default'], *alternatives], many)
                    block['fields'][name]['previousDefault'] = old['default']


