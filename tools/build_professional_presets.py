import json
from pathlib import Path


def text(default, description=''):
    return {'type': 'text', 'default': default, 'description': description}


def select(options, default=None):
    return {'type': 'select', 'options': options, 'default': default or options[0]}


def multi(options, default):
    return {'type': 'multi-select', 'options': options, 'default': default}


def section(**fields):
    return {'fields': fields}


def preset(key, name, description, sections):
    return {'key': key, 'name': name, 'description': description,
            'source': '原创专业预设 · 展台 / 展厅 / 文化墙', 'sections': sections}


